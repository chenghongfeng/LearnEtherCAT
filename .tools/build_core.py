# -*- coding: utf-8 -*-
"""
把 ES module 版本的数据层/UI 层打包成一个 classic 脚本 assets/js/ec-core.js，
并把各页面的 <script type="module"> 改写为 classic 脚本。

原因：Chrome/Firefox 对 file:// 下的 ES module import 做 CORS 拦截
（origin 'null'），双击打开时脚本根本不会执行，所有按钮都会"点不动"。
打包成 classic script 后，file:// 与 http:// 都能正常工作。

用法: python .tools/build_core.py
数据源: assets/js/data.js + assets/js/ui.js （仍是单一事实来源）
输出:   assets/js/ec-core.js（生成物，勿手改）+ 各页面内联脚本改写
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / 'assets' / 'js' / 'data.js'
UI = ROOT / 'assets' / 'js' / 'ui.js'
CORE = ROOT / 'assets' / 'js' / 'ec-core.js'

# 页面里可能出现的 import 写法
IMPORT_RE = re.compile(
    r"^[ \t]*import\s*\{([^}]+)\}\s*from\s*['\"]([^'\"]+)['\"];?[ \t]*\n?",
    re.M,
)
EXPORT_DECL_RE = re.compile(r'^export\s+(const|let|var|function|class)\s+([A-Za-z0-9_$]+)', re.M)
EXPORT_LIST_RE = re.compile(r'^export\s*\{[^}]*\}\s*;?\s*$', re.M)


def strip_exports(src: str):
    names = [m.group(2) for m in EXPORT_DECL_RE.finditer(src)]
    body = EXPORT_DECL_RE.sub(lambda m: f'{m.group(1)} {m.group(2)}', src)
    leftovers = EXPORT_LIST_RE.findall(body)
    body = EXPORT_LIST_RE.sub('', body)
    if re.search(r'^\s*export\s', body, re.M):
        raise SystemExit('仍有未处理的 export 语句')
    return body, names, leftovers


def make_core():
    data_body, data_names, _ = strip_exports(DATA.read_text(encoding='utf-8'))
    ui_body, ui_names, _ = strip_exports(UI.read_text(encoding='utf-8'))

    parts = [
        '/* =========================================================',
        '   AUTO-GENERATED by .tools/build_core.py — 请勿手改',
        '   源文件：assets/js/data.js + assets/js/ui.js',
        '   目的：classic script，file:// 下也能执行（ES module 会被 CORS 拦截）',
        '   ========================================================= */',
        '(function (global) {',
        "  'use strict';",
        '  /* ---------------- data.js ---------------- */',
        data_body,
        f"  global.EC_DATA = {{ {', '.join(data_names)} }};",
        '})(window);',
        '',
        '(function (global) {',
        "  'use strict';",
        '  /* ---------------- ui.js ---------------- */',
        ui_body,
        f"  global.EC_UI = {{ {', '.join(ui_names)} }};",
        '})(window);',
        '',
    ]
    CORE.write_text('\n'.join(parts), encoding='utf-8')
    print(f'wrote {CORE.relative_to(ROOT)} ({CORE.stat().st_size/1024:.1f} KB)')
    return data_names, ui_names


def to_globals(names: str, global_name: str) -> str:
    pairs = []
    for part in names.split(','):
        part = part.strip()
        if not part:
            continue
        if ' as ' in part:
            orig, alias = [x.strip() for x in part.split(' as ')]
            pairs.append(f'{orig}: {alias}')
        else:
            pairs.append(part)
    return f"const {{ {', '.join(pairs)} }} = {global_name};" if pairs else ''


def convert_page(path: pathlib.Path):
    html = path.read_text(encoding='utf-8')
    if 'assets/js/ec-core.js' in html and '<script type="module">' not in html:
        print(f'  skip {path.name}（已是 classic）')
        return False

    m = re.search(r'<script type="module">\n(.*?)\n</script>', html, re.S)
    if not m:
        print(f'  ! {path.name} 没找到 module 脚本，跳过')
        return False

    code = m.group(1)
    imports = []

    def take_import(mm):
        imports.append((mm.group(1), mm.group(2)))
        return ''

    code = IMPORT_RE.sub(take_import, code)

    decls = []
    for names, src in imports:
        if src.endswith('data.js'):
            decls.append(to_globals(names, 'EC_DATA'))
        elif src.endswith('ui.js'):
            decls.append(to_globals(names, 'EC_UI'))
        else:
            raise SystemExit(f'{path.name}: 未知模块 {src}')

    replacement = (
        '<script src="assets/js/ec-core.js"></script>\n'
        '<script>\n'
        + '\n'.join(d for d in decls if d) + '\n'
        + code + '\n'
        '</script>'
    )
    html = html[:m.start()] + replacement + html[m.end():]
    path.write_text(html, encoding='utf-8')
    print(f'  convert {path.name}（imports: {len(imports)}）')
    return True


def main():
    make_core()
    print('pages:')
    for p in sorted(ROOT.glob('*.html')):
        convert_page(p)


if __name__ == '__main__':
    main()
